// Renders switch/orderroom.template.yaml from agent/INSTRUCTIONS.md and agent/ROOM-office.md,
// so the instructions in Switch never drift from the ones in the repo. `--check` fails on drift (CI).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "../src/db/client.js";

const DISALLOWED = JSON.parse(
  readFileSync(join(REPO_ROOT, "agent", ".claude", "settings.json"), "utf8"),
).permissions.deny as string[];

function block(text: string, indent: number): string {
  const pad = " ".repeat(indent);
  return text
    .trimEnd()
    .split("\n")
    .map((l) => (l ? pad + l : ""))
    .join("\n");
}

export function renderTemplate(): string {
  const instructions = readFileSync(join(REPO_ROOT, "agent", "INSTRUCTIONS.md"), "utf8");
  const office = readFileSync(join(REPO_ROOT, "agent", "ROOM-office.md"), "utf8");
  return `# OrderRoom — Switch template (generated by scripts/build-template.ts; edit agent/*.md instead)
# Import: Switch Console → Templates → Import template → this file → Use.
# Run \`npm run setup\` first; it prints the absolute agent directory to paste below.
# The form pre-fills the box with the literal text {directory}: clear it, paste the bare path, no braces.
version: 2
params:
  team:
    type: string
    label: Team name
    default: orderroom
    pattern: "[a-z][a-z0-9-]*"
  directory:
    type: directory
    label: OrderRoom agent directory
    description: "Absolute path printed by npm run setup, e.g. /Users/you/orderroom/agent. Clear the box first; no { } braces."
    input: ask
  bridge:
    type: bridge
    label: Office chat app
    default: [Mattermost, $first]
  machine:
    type: machine
    default: [$first]
    input: advanced
resources:
  desk:
    type: agent
    name: "{team}-agent"
    display_name: OrderRoom desk
    description: Order desk for an FMCG distributor. Credit, stock and approval rules are enforced in code.
    provider: claude
    machine: "{machine}"
    directory: "{directory}"
    model: sonnet
    addressing: anyone
    auto_mode: true
    auto_approve: false
    advanced_config:
      tools: [mcp__orderroom]
      disallowedTools: [${DISALLOWED.join(", ")}]
      maxTurns: 20
    instructions: |
${block(instructions, 6)}
  office:
    type: room
    name: "{team}-office"
    description: Office room for the manager, godown and delivery. Approvals, bills, pick lists and the DSR.
    bridge: "{bridge}"
    agents: [desk]
    users: ["{$creator}"]
    aliases: { desk: desk }
    instructions: |
${block(office, 6)}
    kickoff: "@desk introduce yourself in two lines, then post today's low-stock SKUs."
`;
}

const out = join(REPO_ROOT, "switch", "orderroom.template.yaml");
const yaml = renderTemplate();
if (process.argv.includes("--check")) {
  const cur = readFileSync(out, "utf8");
  if (cur !== yaml) {
    console.error("switch/orderroom.template.yaml is stale: run npm run template");
    process.exit(1);
  }
  console.log("template up to date");
} else {
  writeFileSync(out, yaml);
  console.log(`[template] wrote ${out}`);
}
