// LLD §10 Bill: A5 PDF with ₹ (Noto Sans; pdfkit's built-in Helvetica has no ₹ glyph).
// Generated after the transaction commits; the caller stores bill_path in a second small update.
import { createWriteStream, mkdirSync } from "node:fs";
import { join } from "node:path";
import PDFDocument from "pdfkit";
import { dataDir, REPO_ROOT } from "../db/client.js";
import { istDate, now } from "./clock.js";
import { rupeesExact } from "./money.js";
import type { ConfirmResult } from "./orders.js";

const FONT = join(REPO_ROOT, "fonts", "NotoSans-Regular.ttf");
const FONT_BOLD = join(REPO_ROOT, "fonts", "NotoSans-Bold.ttf");

export async function writeBillPdf(
  c: ConfirmResult,
  dir = join(dataDir(), "bills"),
): Promise<string> {
  if (!c.bill_no) throw new Error("order has no bill number");
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${c.bill_no}.pdf`);
  const doc = new PDFDocument({
    size: "A5",
    margin: 32,
    info: { Title: c.bill_no, Author: "OrderRoom (demo)" },
  });
  doc.registerFont("r", FONT);
  doc.registerFont("b", FONT_BOLD);
  const out = createWriteStream(path);
  const done = new Promise<void>((res, rej) => {
    out.on("finish", () => res());
    out.on("error", rej);
  });
  doc.pipe(out);

  const W = doc.page.width - 64;
  doc.font("b").fontSize(14).text("OrderRoom Distributors (demo)");
  doc
    .font("r")
    .fontSize(8)
    .fillColor("#555")
    .text("Made-up distributor for the Flip the Switch hackathon · not a real tax invoice");
  doc.moveDown(0.6).fillColor("#000");
  doc.font("b").fontSize(11).text(`Bill ${c.bill_no}`, { continued: true });
  doc
    .font("r")
    .fontSize(9)
    .text(`   Order #${c.order_id} · ${istDate(now())}`, { align: "left" });
  doc.moveDown(0.3);
  doc.font("b").fontSize(10).text(c.party.name);
  doc.font("r").fontSize(9).text(`${c.party.area} · ${c.party.code}`);
  doc.moveDown(0.6);

  const cols = [0, 0.5, 0.6, 0.71, 0.84].map((f) => 32 + f * W);
  const header = ["Item", "Cases", "Units", "Rate", "Amount"];
  const row = (cells: string[], bold = false) => {
    const y = doc.y;
    doc.font(bold ? "b" : "r").fontSize(8.5);
    let h = 0;
    cells.forEach((t, i) => {
      const x = cols[i] ?? 32;
      const width = (cols[i + 1] ?? 32 + W) - x - 4;
      const opts = { width, align: i === 0 ? ("left" as const) : ("right" as const) };
      h = Math.max(h, doc.heightOfString(t || " ", opts));
      doc.text(t, x, y, opts);
    });
    doc.x = 32;
    doc.y = y + h + 3;
  };
  row(header, true);
  doc
    .moveTo(32, doc.y)
    .lineTo(32 + W, doc.y)
    .strokeColor("#999")
    .stroke();
  doc.moveDown(0.25);
  for (const b of c.bill_lines) {
    if (b.cases > 0) {
      row([
        `${b.name} · ${b.gst_pct}%`,
        String(b.cases),
        String(b.units),
        rupeesExact(b.unit_price),
        rupeesExact(b.amount),
      ]);
    }
    if (b.free > 0)
      row([
        `Scheme free (${b.name})`,
        String(b.free),
        String(b.free * b.case_size),
        rupeesExact(0),
        rupeesExact(0),
      ]);
    if (b.backordered > 0)
      row([`Backorder, not billed (${b.name})`, String(b.backordered), "", "", ""]);
  }
  doc
    .moveTo(32, doc.y)
    .lineTo(32 + W, doc.y)
    .stroke();
  doc.moveDown(0.3);
  const total = (label: string, v: number, bold = false) =>
    row([label, "", "", "", rupeesExact(v)], bold);
  total("Subtotal", c.subtotal);
  for (const [rate, t] of Object.entries(c.tax_by_rate)) if (t > 0) total(`GST ${rate}%`, t);
  total("Total", c.total, true);
  doc.moveDown(0.8);
  if (c.approved_by) doc.font("r").fontSize(9).text(`Approved by ${c.approved_by}`);
  if (c.backorders.length) {
    doc
      .fontSize(8)
      .text(`Backorder: ${c.backorders.map((b) => `${b.name} ${b.qty} cs`).join(", ")}`);
  }
  doc
    .moveDown(1)
    .fontSize(7.5)
    .fillColor("#777")
    .text("Generated by OrderRoom via Switch · all names and prices are made up");
  doc.end();
  await done;
  return path;
}
